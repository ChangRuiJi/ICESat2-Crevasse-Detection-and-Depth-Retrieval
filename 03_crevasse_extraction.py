"""
Thin-plate-spline surface reconstruction and automatic crevasse extraction
from denoised ICESat-2 ATL03 photons.

Input
-----
The input is the six-column output generated by Denoising_GitHub.py:
    0: along-track distance (m)
    1: elevation (m)
    2: UTM easting (m)
    3: UTM northing (m)
    4: longitude (degrees)
    5: latitude (degrees)

Only along-track distance and elevation are used for reconstruction and
crevasse extraction. The remaining columns are retained by the upstream
denoising module for geospatial reference.

Workflow
--------
1. Calculate 5-m mean elevation points.
2. Reconstruct the glacier surface using thin-plate-spline interpolation.
3. Optionally refine preliminary valley bottoms using retained-photon clusters.
4. Identify local minima and prominent shoulders.
5. Estimate individual crevasse depth and effective width.
6. Merge adjacent candidates belonging to complex crevasses.
7. Retain crevasses satisfying BOTH final criteria:
       depth > 3 m and width < 150 m
   The depth/width ratio is reported as a descriptive attribute only; it is
   not used as a screening threshold.

Outputs
-------
A crevasse table (TXT) and a diagnostic plot (PNG) are saved in
`crevasse_output/`.

Dependencies
------------
numpy, scipy, matplotlib

Run
---
Run Denoising_GitHub.py first, then run this script from the repository root.
"""


