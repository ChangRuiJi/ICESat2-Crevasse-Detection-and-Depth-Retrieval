# ============================================================
# 7. Thin Plate Spline
# ============================================================

def thin_plate_spline_fit(
        x,
        y,
        xi,
        smooth=1.0,
        function="thin_plate"
):

    rbf = Rbf(
        x,
        y,
        function=function,
        smooth=smooth
    )

    yi = rbf(
        xi
    )

    return yi


# ============================================================
# 8. Original local-extrema search
# ============================================================

def find_local_extrema(lst):

    result = []


    for i in range(
        1,
        len(lst) - 1
    ):


        # ----------------------------------------------------
        # local maximum
        # ----------------------------------------------------

        if (
            lst[i] > lst[i - 1]
            and
            lst[i] > lst[i + 1]
        ):

            result.append(
                (
                    i,
                    lst[i],
                    "max"
                )
            )


        # ----------------------------------------------------
        # local minimum
        # ----------------------------------------------------

        elif (
            lst[i] < lst[i - 1]
            and
            lst[i] < lst[i + 1]
        ):

            result.append(
                (
                    i,
                    lst[i],
                    "min"
                )
            )


    return result


# ============================================================
# 9. NEW:
# Find nearest PROMINENT shoulders
# ============================================================

def find_prominent_shoulders(
        x,
        y,
        min_index,
        prominence_threshold=1.5,
        max_distance=200.0
):
    """
    Search the nearest physically significant local maximum
    on each side of a crevasse minimum.

    Small local undulations on crevasse walls are ignored
    through the peak-prominence criterion.

    Parameters
    ----------
    x : array
        Along-track coordinates of reconstructed surface.

    y : array
        Reconstructed elevations.

    min_index : int
        Index of current local minimum in x/y.

    prominence_threshold : float
        Minimum peak prominence in metres.

    max_distance : float
        Maximum allowable distance from valley bottom to
        each shoulder.

    Returns
    -------
    left_idx, right_idx
        Indices in x/y of the selected shoulders.
    """


    # ========================================================
    # Find all significant peaks
    # ========================================================

    peak_idx, properties = find_peaks(
        y,
        prominence=prominence_threshold
    )


    if len(peak_idx) == 0:

        return None, None


    valley_x = x[
        min_index
    ]


    # ========================================================
    # Peaks on left and right
    # ========================================================

    left_peaks = peak_idx[
        peak_idx < min_index
    ]


    right_peaks = peak_idx[
        peak_idx > min_index
    ]


    if (
        len(left_peaks) == 0
        or
        len(right_peaks) == 0
    ):

        return None, None


    # ========================================================
    # KEY:
    # nearest PROMINENT peak on each side
    # ========================================================

    left_idx = left_peaks[-1]

    right_idx = right_peaks[0]


    # ========================================================
    # Prevent unreasonable distant shoulders
    # ========================================================

    if (
        valley_x
        -
        x[left_idx]
        >
        max_distance
    ):

        return None, None


    if (
        x[right_idx]
        -
        valley_x
        >
        max_distance
    ):

        return None, None


    return (
        left_idx,
        right_idx
    )


# ============================================================
# 9b. NEW:
# Merge adjacent minima belonging to one complex crevasse
# ============================================================

def merge_complex_crevasses(
        crevasse_x,
        crevasse_ele,
        crevasse_depth,
        crevasse_width,
        crevasse_ratio,
        left_x,
        left_ele,
        right_x,
        right_ele,
        cross_x,
        ref_ele,
        surface_x,
        surface_y,
        recovery_tol=2.0
):
    """
    Merge neighboring candidate minima when the ridge between them
    does not recover to the surrounding surface level.

    For every merged group:
      1) keep the deepest minimum as the representative bottom;
      2) use the left shoulder of the first candidate and the right
         shoulder of the last candidate as the enclosing shoulders;
      3) recompute reference elevation, effective width, depth and ratio
         with the same geometric definitions used by the original method.
    """

    if len(crevasse_x) <= 1:
        return (
            np.asarray(crevasse_x),
            np.asarray(crevasse_ele),
            np.asarray(crevasse_depth),
            np.asarray(crevasse_width),
            np.asarray(crevasse_ratio),
            np.asarray(left_x),
            np.asarray(left_ele),
            np.asarray(right_x),
            np.asarray(right_ele),
            np.asarray(cross_x),
            np.asarray(ref_ele)
        )

    # --------------------------------------------------------
    # Sort by along-track position
    # --------------------------------------------------------
    order = np.argsort(crevasse_x)

    cx = np.asarray(crevasse_x)[order]
    ce = np.asarray(crevasse_ele)[order]
    cd = np.asarray(crevasse_depth)[order]
    cw = np.asarray(crevasse_width)[order]
    cr = np.asarray(crevasse_ratio)[order]

    lx = np.asarray(left_x)[order]
    le = np.asarray(left_ele)[order]
    rx = np.asarray(right_x)[order]
    re = np.asarray(right_ele)[order]
    xx = np.asarray(cross_x)[order]
    rr = np.asarray(ref_ele)[order]

    # --------------------------------------------------------
    # Build groups of candidate minima.
    # Merge when the separating crest is still distinctly below
    # the enclosing surface formed by the outer shoulders.
    # --------------------------------------------------------
    groups = []
    current = [0]

    for i in range(len(cx) - 1):

        # Highest reconstructed elevation between the two minima
        mask = (
            (surface_x >= cx[i])
            &
            (surface_x <= cx[i + 1])
        )

        if not np.any(mask):
            groups.append(current)
            current = [i + 1]
            continue

        separating_peak = np.max(surface_y[mask])

        # Use current group's outer-left shoulder and next candidate's
        # outer-right shoulder to estimate the surrounding surface level.
        group_left = current[0]
        outer_level = min(
            le[group_left],
            re[i + 1]
        )

        # If the crest does not recover to the surrounding surface,
        # it is an internal ridge of the same complex crevasse.
        if separating_peak < outer_level - recovery_tol:
            current.append(i + 1)
        else:
            groups.append(current)
            current = [i + 1]

    groups.append(current)

    # --------------------------------------------------------
    # Recompute one crevasse geometry for each merged group
    # --------------------------------------------------------
    out_x = []
    out_ele = []
    out_depth = []
    out_width = []
    out_ratio = []
    out_lx = []
    out_le = []
    out_rx = []
    out_re = []
    out_cross = []
    out_ref = []

    for group in groups:

        first = group[0]
        last = group[-1]

        # deepest minimum in the group
        best_local = group[int(np.argmin(ce[group]))]

        point_min_x = cx[best_local]
        point_min_ele = ce[best_local]

        # enclosing shoulders of the whole complex crevasse
        point_left_x = lx[first]
        point_left_ele = le[first]
        point_right_x = rx[last]
        point_right_ele = re[last]

        left_idx = int(np.argmin(np.abs(surface_x - point_left_x)))
        right_idx = int(np.argmin(np.abs(surface_x - point_right_x)))

        if right_idx <= left_idx:
            continue

        # ----------------------------------------------------
        # Same reference-height rule as the original method
        # ----------------------------------------------------
        if point_right_ele < point_left_ele:
            reference_ele = point_right_ele
            depth = reference_ele - point_min_ele

            crossings = []
            for k in range(left_idx, right_idx):
                if k >= len(surface_x) - 1:
                    continue

                v1 = surface_y[k] - reference_ele
                v2 = surface_y[k + 1] - reference_ele

                if v1 * v2 < 0:
                    crossings.append(
                        (surface_x[k] + surface_x[k + 1]) / 2.0
                    )

            valid = [c for c in crossings if c < point_min_x]
            if len(valid) == 0:
                continue

            crossing_x = max(valid)
            width = point_right_x - crossing_x

        else:
            reference_ele = point_left_ele
            depth = reference_ele - point_min_ele

            crossings = []
            for k in range(left_idx, right_idx):
                if k >= len(surface_x) - 1:
                    continue

                v1 = surface_y[k] - reference_ele
                v2 = surface_y[k + 1] - reference_ele

                if v1 * v2 < 0:
                    crossings.append(
                        (surface_x[k] + surface_x[k + 1]) / 2.0
                    )

            valid = [c for c in crossings if c > point_min_x]
            if len(valid) == 0:
                continue

            crossing_x = min(valid)
            width = crossing_x - point_left_x

        if width <= 0 or depth <= 0:
            continue

        ratio = depth / width

        # Apply the final depth and width thresholds only.
        if (
            depth > DEPTH_THRESHOLD
            and
            width < WIDTH_THRESHOLD
        ):
            out_x.append(point_min_x)
            out_ele.append(point_min_ele)
            out_depth.append(depth)
            out_width.append(width)
            out_ratio.append(ratio)
            out_lx.append(point_left_x)
            out_le.append(point_left_ele)
            out_rx.append(point_right_x)
            out_re.append(point_right_ele)
            out_cross.append(crossing_x)
            out_ref.append(reference_ele)

    return (
        np.asarray(out_x),
        np.asarray(out_ele),
        np.asarray(out_depth),
        np.asarray(out_width),
        np.asarray(out_ratio),
        np.asarray(out_lx),
        np.asarray(out_le),
        np.asarray(out_rx),
        np.asarray(out_re),
        np.asarray(out_cross),
        np.asarray(out_ref)
    )


def main():
    """Run surface reconstruction and automatic crevasse extraction."""

    # ============================================================
    # 10. Read denoised photons from the preceding module
    # ============================================================

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    if not DENOISED_FILE.is_file():
        raise FileNotFoundError(
            f"Denoised input file not found: {DENOISED_FILE}\n"
            "Run Denoising_GitHub.py first and check DENOISED_FILE."
        )

    denoised = np.loadtxt(
        DENOISED_FILE,
        delimiter=",",
        dtype=float,
        ndmin=2
    )

    if denoised.shape[1] != 6:
        raise ValueError(
            "The denoised input must contain exactly six columns in this order: "
            "along-track distance, elevation, easting, northing, longitude, latitude. "
            f"Found {denoised.shape[1]} columns."
        )

    # The fitting and crevasse-extraction steps use the first two columns only.
    valid = np.all(np.isfinite(denoised[:, :2]), axis=1)
    denoised = denoised[valid]

    if len(denoised) < 3:
        raise RuntimeError("At least three valid denoised photons are required.")

    denoised = denoised[np.argsort(denoised[:, 0])]

    # Optional along-track subset. The default is to process the complete file.
    if X_START is not None:
        denoised = denoised[denoised[:, 0] >= X_START]
    if X_END is not None:
        denoised = denoised[denoised[:, 0] <= X_END]

    if len(denoised) < 3:
        raise RuntimeError("Fewer than three denoised photons remain in the selected range.")

    Along_Track = denoised[:, 0]
    Elevation = denoised[:, 1]

    # Optional background photons are used for visualization only and do not
    # participate in surface reconstruction or crevasse extraction.
    raw_plot = None
    if BACKGROUND_FILE is not None:
        background_path = Path(BACKGROUND_FILE)
        if not background_path.is_file():
            raise FileNotFoundError(f"Background photon file not found: {background_path}")

        background = np.loadtxt(
            background_path,
            delimiter=",",
            dtype=float,
            ndmin=2
        )
        if background.shape[1] < 2:
            raise ValueError("The optional background file must contain at least two columns.")

        background = background[np.all(np.isfinite(background[:, :2]), axis=1)]
        if X_START is not None:
            background = background[background[:, 0] >= X_START]
        if X_END is not None:
            background = background[background[:, 0] <= X_END]
        raw_plot = background

    # Output filename follows the input filename automatically.
    OUTPUT_FILE = OUTPUT_DIR / f"{DENOISED_FILE.stem}_crevasses.txt"

    print("\n===================================")
    print("Denoised photons for crevasse extraction")
    print("===================================")
    print(f"Input file: {DENOISED_FILE}")
    print(f"Photon number: {len(denoised):,}")
    print(f"Along-track range: {Along_Track.min():.3f} - {Along_Track.max():.3f} m")
    print(f"Elevation range: {Elevation.min():.3f} - {Elevation.max():.3f} m")
    print(f"Depth threshold: > {DEPTH_THRESHOLD:.2f} m")
    print(f"Width threshold: < {WIDTH_THRESHOLD:.2f} m")


    # ============================================================
    # 12. 5-m mean points
    # ============================================================

    x_mean = []

    ele_mean = []


    starts = np.arange(
        Along_Track.min(),
        Along_Track.max(),
        MEAN_WINDOW
    )


    for s in starts:


        left = np.searchsorted(
            Along_Track,
            s
        )


        right = np.searchsorted(
            Along_Track,
            s + MEAN_WINDOW
        )


        if right <= left:

            continue


        x_seg = Along_Track[
            left:right
        ]


        ele_seg = Elevation[
            left:right
        ]


        x_mean.append(
            np.mean(
                x_seg
            )
        )


        ele_mean.append(
            np.mean(
                ele_seg
            )
        )


    x_mean = np.asarray(
        x_mean
    )


    ele_mean = np.asarray(
        ele_mean
    )


    if len(x_mean) < 3:

        raise RuntimeError(
            "Too few 5-m mean points for TPS fitting."
        )


    # ============================================================
    # 13. TPS reconstruction
    #
    # Two-stage reconstruction:
    #   Stage 1: original TPS from 5-m mean points.
    #   Stage 2: identify prominent preliminary valleys, locate the
    #            dominant bottom-photon cluster around each valley, use
    #            the cluster centre as a bottom anchor, and refit TPS.
    #
    # This keeps the original large-scale smoothness while reducing the
    # upward bias of deep/narrow crevasse bottoms caused by 5-m averaging.
    # ============================================================

    number = int(
        (
            Along_Track.max()
            -
            Along_Track.min()
        )
        /
        INTERPOLATION_RESOLUTION
    )


    if number < 3:

        raise RuntimeError(
            "Too few interpolation points."
        )


    x1 = np.linspace(
        Along_Track.min(),
        Along_Track.max(),
        number
    )


    # ------------------------------------------------------------
    # Stage 1: preliminary TPS using the original 5-m mean points
    # ------------------------------------------------------------

    y1_preliminary = thin_plate_spline_fit(
        x_mean,
        ele_mean,
        x1,
        smooth=TPS_SMOOTH,
        function="thin_plate"
    )


    # ------------------------------------------------------------
    # Stage 2: robust bottom-anchor refinement
    # ------------------------------------------------------------

    bottom_anchor_x = []
    bottom_anchor_z = []

    if BOTTOM_REFINEMENT:

        # Find only physically meaningful preliminary valleys.
        # find_peaks(-surface) returns minima of the reconstructed profile.
        preliminary_min_idx, _ = find_peaks(
            -y1_preliminary,
            prominence=BOTTOM_ANCHOR_PROMINENCE
        )

        for idx in preliminary_min_idx:

            valley_x0 = x1[idx]
            valley_z0 = y1_preliminary[idx]

            local_mask = (
                (Along_Track >= valley_x0 - BOTTOM_SEARCH_RADIUS)
                &
                (Along_Track <= valley_x0 + BOTTOM_SEARCH_RADIUS)
            )

            if np.sum(local_mask) < BOTTOM_MIN_PHOTONS:
                continue

            local_x = Along_Track[local_mask]
            local_z = Elevation[local_mask]

            # ----------------------------------------------------
            # Identify the CENTER of the bottom photon cluster.
            #
            # 1) Restrict the search to a low-elevation band around the
            #    preliminary TPS valley.  This removes most wall photons
            #    above the floor and very low isolated residuals.
            # 2) Build an elevation histogram from retained photons.
            # 3) Locate the dominant low-elevation photon cluster.
            # 4) Use the MEDIAN elevation of photons around that peak as
            #    the bottom anchor, i.e. the centre of the photon cluster.
            # ----------------------------------------------------

            low_band_mask = (
                (local_z >= valley_z0 - BOTTOM_CLUSTER_LOWER_MARGIN)
                &
                (local_z <= valley_z0 + BOTTOM_CLUSTER_UPPER_MARGIN)
            )

            if np.sum(low_band_mask) < BOTTOM_MIN_CLUSTER_PHOTONS:
                continue

            band_x = local_x[low_band_mask]
            band_z = local_z[low_band_mask]

            z_min = np.floor(band_z.min() / BOTTOM_HIST_BIN) * BOTTOM_HIST_BIN
            z_max = np.ceil(band_z.max() / BOTTOM_HIST_BIN) * BOTTOM_HIST_BIN

            if z_max <= z_min:
                anchor_x = np.median(band_x)
                anchor_z = np.median(band_z)

            else:
                z_edges = np.arange(
                    z_min,
                    z_max + BOTTOM_HIST_BIN,
                    BOTTOM_HIST_BIN
                )

                # The denoising output contains six geographic/position columns;
                # it does not contain the similarity-weighted density as a column.
                # Therefore, identify the dominant bottom cluster using photon
                # counts rather than accidentally treating easting as a weight.
                hist, edges = np.histogram(
                    band_z,
                    bins=z_edges
                )

                if len(hist) == 0 or np.max(hist) <= 0:
                    anchor_x = np.median(band_x)
                    anchor_z = np.median(band_z)

                else:
                    peak_idx = int(np.argmax(hist))
                    peak_z = (edges[peak_idx] + edges[peak_idx + 1]) / 2.0

                    cluster_mask = (
                        (band_z >= peak_z - BOTTOM_CLUSTER_HALF_WIDTH)
                        &
                        (band_z <= peak_z + BOTTOM_CLUSTER_HALF_WIDTH)
                    )

                    if np.sum(cluster_mask) < BOTTOM_MIN_CLUSTER_PHOTONS:
                        # Fallback: use photons in the peak histogram bin.
                        cluster_mask = (
                            (band_z >= edges[peak_idx])
                            &
                            (band_z < edges[peak_idx + 1])
                        )

                    if np.sum(cluster_mask) == 0:
                        continue

                    cluster_x = band_x[cluster_mask]
                    cluster_z = band_z[cluster_mask]

                    # KEY: use the middle of the photon cluster, not its
                    # lowest photons. Median is robust to a few residuals.
                    anchor_x = np.median(cluster_x)
                    anchor_z = np.median(cluster_z)

            # Only correct valleys that are demonstrably too shallow in
            # the preliminary 5-m-mean TPS reconstruction.
            if anchor_z < valley_z0 - BOTTOM_MIN_CORRECTION:

                bottom_anchor_x.append(anchor_x)
                bottom_anchor_z.append(anchor_z)


    # Convert to arrays
    bottom_anchor_x = np.asarray(
        bottom_anchor_x,
        dtype=float
    )

    bottom_anchor_z = np.asarray(
        bottom_anchor_z,
        dtype=float
    )


    if BOTTOM_REFINEMENT and len(bottom_anchor_x) > 0:

        # Remove the original 5-m mean control point nearest each bottom
        # anchor.  Otherwise a high 5-m mean and a low floor anchor at
        # almost the same x coordinate would compete in the TPS fit.
        keep_mean = np.ones(
            len(x_mean),
            dtype=bool
        )

        for ax0 in bottom_anchor_x:

            nearest = int(
                np.argmin(
                    np.abs(x_mean - ax0)
                )
            )

            keep_mean[nearest] = False

        x_control = np.concatenate(
            (
                x_mean[keep_mean],
                bottom_anchor_x
            )
        )

        z_control = np.concatenate(
            (
                ele_mean[keep_mean],
                bottom_anchor_z
            )
        )

        control_order = np.argsort(
            x_control
        )

        x_control = x_control[control_order]
        z_control = z_control[control_order]

        y1 = thin_plate_spline_fit(
            x_control,
            z_control,
            x1,
            smooth=BOTTOM_REFINE_SMOOTH,
            function="thin_plate"
        )

    else:

        # Fall back to the original reconstruction if no reliable bottom
        # anchors are available.
        y1 = y1_preliminary.copy()


    print(
        "\nTPS interpolation points:",
        len(x1)
    )

    print(
        "Bottom anchors used:",
        len(bottom_anchor_x)
    )

    if len(bottom_anchor_x) > 0:

        preliminary_at_anchor = np.interp(
            bottom_anchor_x,
            x1,
            y1_preliminary
        )

        correction = (
            preliminary_at_anchor
            -
            bottom_anchor_z
        )

        print(
            "Mean bottom correction:",
            np.mean(correction),
            "m"
        )

        print(
            "Maximum bottom correction:",
            np.max(correction),
            "m"
        )


    # ============================================================
    # 14. Search original local extrema
    #
    # Important:
    # save index of every minimum because prominent shoulders
    # are searched directly on the TPS profile.
    # ============================================================

    extrema = find_local_extrema(
        y1
    )


    min_idx = []

    min_x = []

    min_ele = []


    max_idx = []

    max_x = []

    max_ele = []


    for item in extrema:


        index = item[0]

        elevation = item[1]

        point_type = item[2]


        if point_type == "min":


            min_idx.append(
                index
            )


            min_x.append(
                x1[index]
            )


            min_ele.append(
                elevation
            )


        else:


            max_idx.append(
                index
            )


            max_x.append(
                x1[index]
            )


            max_ele.append(
                elevation
            )


    # ============================================================
    # 15. Arrays for results
    # ============================================================

    crevasse_x = []

    crevasse_ele = []


    crevasse_depth = []

    crevasse_width = []

    crevasse_ratio = []


    # plotting geometry

    crevasse_left_x = []

    crevasse_left_ele = []


    crevasse_right_x = []

    crevasse_right_ele = []


    crevasse_cross_x = []

    crevasse_ref_ele = []


    # ============================================================
    # 16. Automatic crevasse extraction
    #
    # Difference from previous version:
    #
    # shoulder = nearest PROMINENT peak
    #
    # depth / width definitions remain ORIGINAL.
    # ============================================================

    for j in range(
        len(min_idx)
    ):


        # ========================================================
        # Current minimum
        # ========================================================

        point_min_idx = min_idx[j]


        point_min_x = x1[
            point_min_idx
        ]


        point_min_ele = y1[
            point_min_idx
        ]


        # ========================================================
        # Find nearest significant shoulders
        # ========================================================

        left_idx, right_idx = (
            find_prominent_shoulders(
                x1,
                y1,

                point_min_idx,

                prominence_threshold=
                PEAK_PROMINENCE,

                max_distance=
                MAX_SHOULDER_DISTANCE
            )
        )


        if (
            left_idx is None
            or
            right_idx is None
        ):

            continue


        point_left_x = x1[
            left_idx
        ]


        point_left_ele = y1[
            left_idx
        ]


        point_right_x = x1[
            right_idx
        ]


        point_right_ele = y1[
            right_idx
        ]


        depth = 0.0

        width = 0.0

        crossing_x = np.nan

        reference_ele = np.nan


        # ========================================================
        # CASE 1
        #
        # Right shoulder is LOWER
        #
        # reference elevation = right shoulder
        # ========================================================

        if (
            point_right_ele
            <
            point_left_ele
        ):


            reference_ele = (
                point_right_ele
            )


            depth = (
                point_right_ele
                -
                point_min_ele
            )


            # ----------------------------------------------------
            # Search crossings with reference elevation
            # ----------------------------------------------------

            crossing_candidates = []


            for k in range(
                left_idx,
                right_idx
            ):


                if k >= len(x1) - 1:

                    continue


                v1 = (
                    y1[k]
                    -
                    reference_ele
                )


                v2 = (
                    y1[k + 1]
                    -
                    reference_ele
                )


                if (
                    v1 * v2
                    <
                    0
                ):


                    crossing_candidates.append(
                        (
                            x1[k]
                            +
                            x1[k + 1]
                        )
                        /
                        2.0
                    )


            # ----------------------------------------------------
            # Need crossing on LEFT side of valley
            #
            # Choose one closest to valley bottom.
            # ----------------------------------------------------

            valid_cross = [
                c
                for c in crossing_candidates
                if c < point_min_x
            ]


            if len(valid_cross) > 0:


                crossing_x = max(
                    valid_cross
                )


                width = (
                    point_right_x
                    -
                    crossing_x
                )


        # ========================================================
        # CASE 2
        #
        # Left shoulder is LOWER
        #
        # reference elevation = left shoulder
        # ========================================================

        else:


            reference_ele = (
                point_left_ele
            )


            depth = (
                point_left_ele
                -
                point_min_ele
            )


            crossing_candidates = []


            for k in range(
                left_idx,
                right_idx
            ):


                if k >= len(x1) - 1:

                    continue


                v1 = (
                    y1[k]
                    -
                    reference_ele
                )


                v2 = (
                    y1[k + 1]
                    -
                    reference_ele
                )


                if (
                    v1 * v2
                    <
                    0
                ):


                    crossing_candidates.append(
                        (
                            x1[k]
                            +
                            x1[k + 1]
                        )
                        /
                        2.0
                    )


            # ----------------------------------------------------
            # Need crossing on RIGHT side of valley
            # ----------------------------------------------------

            valid_cross = [
                c
                for c in crossing_candidates
                if c > point_min_x
            ]


            if len(valid_cross) > 0:


                crossing_x = min(
                    valid_cross
                )


                width = (
                    crossing_x
                    -
                    point_left_x
                )


        # ========================================================
        # Validity checks
        # ========================================================

        if (
            not np.isfinite(
                crossing_x
            )
        ):

            continue


        if width <= 0:

            continue


        if depth <= 0:

            continue


        ratio = (
            depth
            /
            width
        )


        # ========================================================
        # Final depth and width thresholds
        # ========================================================

        if (
            depth > DEPTH_THRESHOLD
            and
            width < WIDTH_THRESHOLD
        ):


            crevasse_x.append(
                point_min_x
            )


            crevasse_ele.append(
                point_min_ele
            )


            crevasse_depth.append(
                depth
            )


            crevasse_width.append(
                width
            )


            crevasse_ratio.append(
                ratio
            )


            crevasse_left_x.append(
                point_left_x
            )


            crevasse_left_ele.append(
                point_left_ele
            )


            crevasse_right_x.append(
                point_right_x
            )


            crevasse_right_ele.append(
                point_right_ele
            )


            crevasse_cross_x.append(
                crossing_x
            )


            crevasse_ref_ele.append(
                reference_ele
            )


    # ============================================================
    # 17. Convert to arrays
    # ============================================================

    crevasse_x = np.asarray(
        crevasse_x
    )

    crevasse_ele = np.asarray(
        crevasse_ele
    )


    crevasse_depth = np.asarray(
        crevasse_depth
    )

    crevasse_width = np.asarray(
        crevasse_width
    )

    crevasse_ratio = np.asarray(
        crevasse_ratio
    )


    crevasse_left_x = np.asarray(
        crevasse_left_x
    )

    crevasse_left_ele = np.asarray(
        crevasse_left_ele
    )


    crevasse_right_x = np.asarray(
        crevasse_right_x
    )

    crevasse_right_ele = np.asarray(
        crevasse_right_ele
    )


    crevasse_cross_x = np.asarray(
        crevasse_cross_x
    )

    crevasse_ref_ele = np.asarray(
        crevasse_ref_ele
    )


    # ============================================================
    # 17b. Merge complex crevasses
    # ============================================================

    print(
        "\nCandidate crevasses before merging:",
        len(crevasse_x)
    )

    (
        crevasse_x,
        crevasse_ele,
        crevasse_depth,
        crevasse_width,
        crevasse_ratio,
        crevasse_left_x,
        crevasse_left_ele,
        crevasse_right_x,
        crevasse_right_ele,
        crevasse_cross_x,
        crevasse_ref_ele
    ) = merge_complex_crevasses(
        crevasse_x,
        crevasse_ele,
        crevasse_depth,
        crevasse_width,
        crevasse_ratio,
        crevasse_left_x,
        crevasse_left_ele,
        crevasse_right_x,
        crevasse_right_ele,
        crevasse_cross_x,
        crevasse_ref_ele,
        x1,
        y1,
        recovery_tol=MERGE_RECOVERY_TOL
    )

    print(
        "Crevasses after merging:",
        len(crevasse_x)
    )


    # ============================================================
    # 18. Statistics
    # ============================================================

    print(
        "\n==================================="
    )

    print(
        "Automatic crevasse extraction"
    )

    print(
        "==================================="
    )


    print(
        "Peak prominence:",
        PEAK_PROMINENCE,
        "m"
    )


    print(
        "Number of crevasses:",
        len(crevasse_x)
    )


    if len(crevasse_x) > 0:


        print(
            "Mean depth:",
            np.mean(
                crevasse_depth
            )
        )


        print(
            "Maximum depth:",
            np.max(
                crevasse_depth
            )
        )


        print(
            "\nIndividual crevasses:"
        )


        for i in range(
            len(crevasse_x)
        ):


            print(
                f"C{i + 1:02d}  "
                f"x={crevasse_x[i]:.2f}  "
                f"depth={crevasse_depth[i]:.2f} m  "
                f"width={crevasse_width[i]:.2f} m  "
                f"ratio={crevasse_ratio[i]:.3f}  "
                f"L={crevasse_left_ele[i]:.2f}  "
                f"R={crevasse_right_ele[i]:.2f}  "
                f"bottom={crevasse_ele[i]:.2f}"
            )


    # ============================================================
    # 19. Save results
    # ============================================================

    output_data = np.column_stack(
        (
            crevasse_x,
            crevasse_ele,
            crevasse_depth,
            crevasse_width,
            crevasse_ratio,
            crevasse_left_x,
            crevasse_left_ele,
            crevasse_right_x,
            crevasse_right_ele,
            crevasse_cross_x,
            crevasse_ref_ele
        )
    ) if len(crevasse_x) > 0 else np.empty((0, 11), dtype=float)

    header = (
        "min_x,min_elevation,"
        "depth,width,ratio,"
        "left_edge_x,left_edge_elevation,"
        "right_edge_x,right_edge_elevation,"
        "crossing_x,reference_elevation"
    )

    np.savetxt(
        OUTPUT_FILE,
        output_data,
        delimiter=",",
        fmt="%.6f",
        header=header,
        comments=""
    )

    print("\nSaved crevasse results to:", OUTPUT_FILE)


    # ============================================================
    # 20. Plot
    # ============================================================

    fig, ax = plt.subplots(
        figsize=FIGSIZE
    )


    # ============================================================
    # A. Optional background photons
    # ============================================================

    if raw_plot is not None and len(raw_plot) > 0:
        ax.scatter(
            raw_plot[:, 0],
            raw_plot[:, 1],
            s=4,
            c="0.75",
            marker=".",
            linewidths=0,
            label="Background photons",
            zorder=1
        )


    # ============================================================
    # B. Denoised signal photons
    # ============================================================

    ax.scatter(
        Along_Track,
        Elevation,
        s=4,
        c="#00BFC4",
        linewidths=0,
        label="Denoised signal photons",
        zorder=2
    )


    # ============================================================
    # C. Reconstructed surface
    # ============================================================

    ax.plot(
        x1,
        y1,

        color="#FF2D20",

        linewidth=2.15,

        label="Reconstructed surface",

        zorder=3
    )


    # ============================================================
    # D. Automatically extracted crevasses
    # ============================================================

    for i in range(
        len(crevasse_x)
    ):


        px = crevasse_x[i]

        py = crevasse_ele[i]


        lx = crevasse_left_x[i]

        ly = crevasse_left_ele[i]


        rx = crevasse_right_x[i]

        ry = crevasse_right_ele[i]


        cx = crevasse_cross_x[i]

        ref = crevasse_ref_ele[i]


        # --------------------------------------------------------
        # Valley bottom
        # --------------------------------------------------------

        ax.scatter(
            px,
            py,

            s=38,

            facecolor="#F4B942",

            edgecolor="black",

            linewidth=0.8,

            zorder=7
        )


        # --------------------------------------------------------
        # Selected PROMINENT shoulders
        # --------------------------------------------------------

        ax.scatter(
            [lx, rx],
            [ly, ry],

            s=30,

            facecolor="white",

            edgecolor="black",

            linewidth=0.9,

            zorder=6
        )


        # --------------------------------------------------------
        # Effective-width crossing point
        # --------------------------------------------------------

        ax.scatter(
            cx,
            ref,

            s=25,

            facecolor="white",

            edgecolor="#D62728",

            linewidth=0.9,

            zorder=7
        )


        # --------------------------------------------------------
        # Depth
        # --------------------------------------------------------

        ax.vlines(
            px,

            py,
            ref,

            colors="#D62728",

            linestyles="--",

            linewidth=1.8,

            alpha=0.90,

            zorder=5
        )


        # --------------------------------------------------------
        # Effective width
        # --------------------------------------------------------

        if (
            ry
            <
            ly
        ):


            width_start = cx

            width_end = rx


        else:


            width_start = lx

            width_end = cx


        ax.hlines(
            ref,

            width_start,
            width_end,

            colors="#4D4D4D",

            linestyles="--",

            linewidth=1.8,

            alpha=0.85,

            zorder=5
        )


    # ============================================================
    # 21. Colorbar
    # ============================================================

    # cbar = fig.colorbar(
    #     sc,
    #     ax=ax,
    #     pad=0.012,
    #     fraction=0.026
    # )
    #
    #
    # cbar.set_label(
    #     "Density",
    #     fontsize=20
    # )
    #
    #
    # cbar.ax.tick_params(
    #     labelsize=16,
    #     direction="out",
    #     length=4
    # )


    # ============================================================
    # 22. Legend
    # ============================================================

    legend_handles = []

    if raw_plot is not None and len(raw_plot) > 0:
        raw_legend = Line2D(
            [0], [0], marker=".", linestyle="None", color="0.75",
            markersize=5, label="Background photons"
        )
        legend_handles.append(raw_legend)

    signal_legend = Line2D(
        [0], [0], marker=".", linestyle="None", color="#00BFC4",
        markersize=7, label="Denoised signal photons"
    )

    surface_legend = Line2D(
        [0], [0], color="#FF2D20", linewidth=1.5,
        label="Reconstructed surface"
    )

    crevasse_legend = Line2D(
        [0], [0], marker="o", linestyle="None",
        markerfacecolor="#F4B942", markeredgecolor="black",
        markersize=7, label="Automatically extracted crevasses"
    )

    edge_legend = Line2D(
        [0], [0], marker="o", linestyle="None",
        markerfacecolor="white", markeredgecolor="black",
        markeredgewidth=0.9, markersize=8, label="Local maxima"
    )

    cross_legend = Line2D(
        [0], [0], marker="o", linestyle="None",
        markerfacecolor="white", markeredgecolor="#D62728",
        markeredgewidth=0.9, markersize=8, label="Width intersections"
    )

    legend_handles.extend([
        signal_legend,
        surface_legend,
        edge_legend,
        cross_legend,
        crevasse_legend
    ])

    ax.legend(
        handles=legend_handles,
        fontsize=LEGEND_SIZE,
        loc="upper right",
        frameon=True,
        markerscale=1.3
    )


    # ============================================================
    # 23. Axis
    # ============================================================

    if X_START is not None or X_END is not None:
        ax.set_xlim(
            X_START if X_START is not None else Along_Track.min(),
            X_END if X_END is not None else Along_Track.max()
        )

    if Y_MIN is not None or Y_MAX is not None:
        ax.set_ylim(
            Y_MIN if Y_MIN is not None else ax.get_ylim()[0],
            Y_MAX if Y_MAX is not None else ax.get_ylim()[1]
        )


    ax.set_xlabel(
        "Along-track distance (m)",
        fontsize=LABEL_SIZE
    )


    ax.set_ylabel(
        "Elevation (m)",
        fontsize=LABEL_SIZE
    )


    ax.tick_params(
        axis="both",

        labelsize=TICK_SIZE,

        direction="out",

        length=5,

        width=1.0
    )


    formatter = ScalarFormatter(
        useOffset=False
    )


    formatter.set_scientific(
        False
    )


    ax.xaxis.set_major_formatter(
        formatter
    )


    for spine in ax.spines.values():

        spine.set_linewidth(
            1.0
        )


    ax.grid(
        False
    )

    ax.set_xlabel(
        "Along-track distance (m)",
        fontsize=30
    )

    ax.set_ylabel(
        "Elevation (m)",
        fontsize=30
    )


    ax.tick_params(
        axis="both",
        labelsize=30,
        direction="out",
    )



    plt.tight_layout()

    if SAVE_FIGURE:
        figure_path = OUTPUT_DIR / f"{DENOISED_FILE.stem}_crevasse_extraction.png"
        fig.savefig(figure_path, dpi=PLOT_DPI, bbox_inches="tight")
        print("Saved diagnostic figure to:", figure_path)

    plt.show()


if __name__ == "__main__":
    main()
