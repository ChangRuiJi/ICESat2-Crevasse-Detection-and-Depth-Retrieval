# ============================================================
# 4. TPS parameters
# ============================================================

MEAN_WINDOW = 5.0

INTERPOLATION_RESOLUTION = 0.7

TPS_SMOOTH = 1.0

# ------------------------------------------------------------
# Bottom-preserving refinement of the reconstructed surface
# ------------------------------------------------------------
# The first TPS fit is still based on the original 5-m mean points.
# Deep/narrow crevasses can be biased upward because wall and bottom
# photons are averaged within the same 5-m window.  A second TPS fit
# is therefore performed after adding robust bottom anchors derived
# directly from the retained signal photons around preliminary valleys.

BOTTOM_REFINEMENT = True

# Only preliminary valleys with at least this prominence are refined.
# Using the same scale as the final minimum depth threshold avoids
# forcing the surface toward small residual undulations.
BOTTOM_ANCHOR_PROMINENCE = 3.0

# Search radius around the preliminary TPS valley position (m).
BOTTOM_SEARCH_RADIUS = 4.0

# Bottom-cluster identification parameters.
# The preliminary TPS minimum is only used to define a low-elevation
# search zone. Within that zone, the dominant vertical photon cluster
# is identified from an elevation histogram of retained photons, and the
# MEDIAN elevation of that cluster is used as the bottom anchor.
# This targets the centre of the crevasse-floor photon cluster rather
# than its lower edge.
BOTTOM_CLUSTER_UPPER_MARGIN = 1.0   # m above preliminary TPS valley
BOTTOM_CLUSTER_LOWER_MARGIN = 12.0  # m below preliminary TPS valley
BOTTOM_HIST_BIN = 0.5               # vertical histogram bin size, m
BOTTOM_CLUSTER_HALF_WIDTH = 1.0     # photons within +/- 1 m of peak

# Minimum numbers of retained photons required for a reliable estimate.
BOTTOM_MIN_PHOTONS = 8
BOTTOM_MIN_CLUSTER_PHOTONS = 4

# Apply an anchor only when it lowers the preliminary TPS valley by
# at least this amount (m).
BOTTOM_MIN_CORRECTION = 0.50

# Smoothing parameter for the second TPS fit.  Keep it identical to
# the original TPS by default so that only the bottom anchors, rather
# than a global change in smoothness, modify the reconstruction.
BOTTOM_REFINE_SMOOTH = TPS_SMOOTH


